// @module: reCart.Contracts.ICartSubsystemContracts
// @purpose: CPU, MemoryBus, dot-stepped 2C02 PPU, 2A03 APU, QuickSave, and RenderBackend subsystem contracts for reCart.
// @depends-on: System, Foundation.Retro
// @exports: ICartMemoryBus, ICartCpuContext, ICartPpuController, ICartApuSink, ICartQuickSaveProvider, ICartRenderBackend

using Foundation.Retro;

namespace reCart.Contracts;

/// <summary>
/// Clean-room <c>2A03</c> 16-bit CPU memory bus and bank-switching control interface.
/// </summary>
public interface ICartMemoryBus
{
    /// <summary>Gets the active switchable PRG-ROM bank slot.</summary>
    uint ActivePrgBank { get; }

    /// <summary>Gets the active switchable CHR pattern bank slot.</summary>
    uint ActiveChrBank { get; }

    /// <summary>Reads a byte from the 16-bit CPU address space (<c>$0000-$FFFF</c>).</summary>
    byte Read(ushort address);

    /// <summary>Writes a byte into the 16-bit CPU address space (<c>$0000-$FFFF</c>).</summary>
    void Write(ushort address, byte value);

    /// <summary>Selects a switchable PRG bank slot.</summary>
    void SwitchPrgBank(uint bank);

    /// <summary>Selects a switchable CHR bank slot.</summary>
    void SwitchChrBank(uint bank);
}

/// <summary>
/// Exposes <c>RP2A03</c> 6502 registers, DMA stalls, interrupts, and snapshots to statically lifted modules.
/// </summary>
public interface ICartCpuContext
{
    /// <summary>Accumulator register (<c>A</c>).</summary>
    byte A { get; set; }

    /// <summary>X index register (<c>X</c>).</summary>
    byte X { get; set; }

    /// <summary>Y index register (<c>Y</c>).</summary>
    byte Y { get; set; }

    /// <summary>Stack pointer offset (<c>$0100 + SP</c>).</summary>
    byte SP { get; set; }

    /// <summary>16-bit program counter (<c>PC</c>).</summary>
    ushort PC { get; set; }

    /// <summary>Processor status flags (<c>NV-BDIZC</c>).</summary>
    byte P { get; set; }

    /// <summary>Total elapsed <c>2A03</c> CPU cycles.</summary>
    ulong CycleCount { get; set; }

    /// <summary>Resets CPU registers and loads <c>$FFFC-$FFFD</c> reset vector.</summary>
    void Reset();

    /// <summary>Asserts a rising-edge non-maskable interrupt (<c>NMI</c>) from the PPU.</summary>
    void RequestNmi();

    /// <summary>Asserts a level-sensitive maskable interrupt (<c>IRQ</c>) from APU or mapper hardware.</summary>
    void RequestIrq();

    /// <summary>Executes an <c>OAMDMA</c> (<c>$4014</c>) transfer with accurate <c>513/514</c> cycle stall accounting.</summary>
    void TriggerOamDma(byte page);

    /// <summary>Applies <c>DMC</c> DMA cycle stealing stall cycles.</summary>
    void ApplyDmcStallCycles(int stallCycles);

    /// <summary>Serializes deterministic CPU state bytes for QuickSave snapshots.</summary>
    byte[] CaptureState();

    /// <summary>Restores deterministic CPU state from a QuickSave snapshot.</summary>
    void RestoreState(ReadOnlySpan<byte> state);
}

/// <summary>
/// Clean-room dot-stepped <c>RP2C02</c> PPU register and framebuffer contract.
/// </summary>
public interface ICartPpuController
{
    /// <summary>Current scanline index within the frame.</summary>
    int Scanline { get; }

    /// <summary>Current PPU dot cycle within the scanline (<c>0..340</c>).</summary>
    int Dot { get; }

    /// <summary>Completed frame counter.</summary>
    long FrameCount { get; }

    /// <summary>Advances the PPU state by one PPU dot and returns <c>true</c> on frame completion.</summary>
    bool StepDot();

    /// <summary>Advances the PPU state across one full scanline (<c>341</c> dots).</summary>
    void StepScanline();

    /// <summary>Returns and clears any pending VBlank NMI edge generated by the PPU.</summary>
    bool TakeNmiPending();

    /// <summary>Writes one byte directly into PPU OAM sprite memory during OAM DMA.</summary>
    void WriteOamByte(byte index, byte value);

    /// <summary>Reads a memory-mapped PPU register (<c>$2000-$2007</c>).</summary>
    byte ReadRegister(ushort address);

    /// <summary>Writes a memory-mapped PPU register (<c>$2000-$2007</c>).</summary>
    void WriteRegister(ushort address, byte value);

    /// <summary>Current <c>256x240</c> RGBA8888 framebuffer ready for host presentation.</summary>
    ReadOnlySpan<byte> FrameBufferRgba { get; }

    /// <summary>Captures deterministic PPU register, VRAM, palette, and OAM state bytes.</summary>
    byte[] CaptureState();

    /// <summary>Restores deterministic PPU state from a QuickSave snapshot.</summary>
    void RestoreState(ReadOnlySpan<byte> state);
}

/// <summary>
/// Clean-room <c>RP2A03</c> APU register sink, DMC stall tracker, and interleaved PCM buffer contract.
/// </summary>
public interface ICartApuSink
{
    /// <summary>Configured stereo output PCM sample rate in hertz.</summary>
    int SampleRateHz { get; }

    /// <summary>Indicates whether the APU frame counter or DMC channel has a pending IRQ.</summary>
    bool IsIrqPending { get; }

    /// <summary>Total ring-buffer audio sample frames dropped due to overflow.</summary>
    long DroppedSampleCount { get; }

    /// <summary>Reads APU status register <c>$4015</c> and clears frame interrupt flags per hardware rules.</summary>
    byte ReadStatus();

    /// <summary>Writes a memory-mapped APU register (<c>$4000-$4017</c>).</summary>
    void WriteRegister(ushort address, byte value);

    /// <summary>Advances APU channels and sample accumulator by one <c>2A03</c> CPU cycle.</summary>
    void ClockCycle();

    /// <summary>Consumes any pending DMC DMA CPU stall cycles generated since the last check.</summary>
    int TakePendingDmcStallCycles();

    /// <summary>Drains available interleaved stereo PCM samples into <paramref name="interleavedStereoPcm"/>.</summary>
    int ReadSamples(Span<short> interleavedStereoPcm);

    /// <summary>Captures deterministic APU channel and frame counter state bytes.</summary>
    byte[] CaptureState();

    /// <summary>Restores deterministic APU state from a QuickSave snapshot.</summary>
    void RestoreState(ReadOnlySpan<byte> state);
}

/// <summary>
/// Deterministic <c>F5</c>/<c>F9</c> machine state snapshot capture and restore contract.
/// </summary>
public interface ICartQuickSaveProvider
{
    /// <summary>Captures a complete deterministic CPU, RAM, PPU, APU, and Mapper snapshot.</summary>
    byte[] CaptureQuickSave();

    /// <summary>Restores a previously captured deterministic machine snapshot.</summary>
    bool TryRestoreQuickSave(ReadOnlySpan<byte> snapshotBytes, out string diagnostic);
}

/// <summary>
/// Render backend abstraction bridging <c>2C02</c> RGBA frames to <c>reEngine.Host</c>.
/// </summary>
public interface ICartRenderBackend : IRecompRenderBackend
{
    /// <summary>Human-readable backend display name.</summary>
    string DisplayName { get; }

    /// <summary>Indicates whether this backend uses hardware GPU acceleration.</summary>
    bool IsHardwareAccelerated { get; }
}

/// <summary>
/// Coordinated cartridge runtime machine uniting CPU, Bus, Dot PPU, APU, Mapper, Input Ports, AOT module dispatch, and QuickSave snapshots.
/// </summary>
public interface ICartMachineRuntime : ICartQuickSaveProvider, IDisposable
{
    /// <summary>Gets the active <c>2A03</c> CPU memory bus.</summary>
    ICartMemoryBus Bus { get; }

    /// <summary>Gets the active <c>2A03</c> CPU register context.</summary>
    ICartCpuContext Cpu { get; }

    /// <summary>Gets the active dot-stepped <c>2C02</c> PPU controller.</summary>
    ICartPpuController Ppu { get; }

    /// <summary>Gets the active <c>2A03</c> APU sink.</summary>
    ICartApuSink Apu { get; }

    /// <summary>Gets the active numeric-ID cartridge mapper.</summary>
    ICartMapper Mapper { get; }

    /// <summary>Gets the active region timing profile.</summary>
    CartRegionTimingProfile TimingProfile { get; }

    /// <summary>Gets mutable execution diagnostics distinguishing static AOT vs quarantined oracle steps.</summary>
    CartExecutionDiagnostics Diagnostics { get; }

    /// <summary>Gets the active execution tier enforcing fail-closed <c>staticAotOnly</c>.</summary>
    CartExecutionTierMode ExecutionTier { get; }

    /// <summary>Updates latched controller bitmask (<c>A, B, Select, Start, Up, Down, Left, Right</c>) for controller port <paramref name="portIndex"/>.</summary>
    void SetControllerButtons(int portIndex, uint nesButtonsMask);

    /// <summary>Binds a statically compiled AOT module and runtime directories onto this machine.</summary>
    void MountStaticModule(ICartRecompGameModule module, ICartModuleManifest manifest, string preloadRomDir, string saveDir);

    /// <summary>Executes one full video frame of CPU, PPU dot rendering, APU sampling, and static/oracle dispatch.</summary>
    void StepFrame(bool fastForward = false);
}

/// <summary>
/// Clean-room static lifting, 3-member <c>.recomp</c> packaging, and cold AOT compilation contract.
/// </summary>
public interface ICartCompilerPipeline
{
    /// <summary>Packages lifted C# sources and <c>module.recomp.json</c> into a strictly 3-member clean-room <c>.recomp</c> archive.</summary>
    string PackageCleanRoomRecomp(ReadOnlySpan<byte> romBytes, CartPackageManifest manifest, string outputRecompZipPath);

    /// <summary>Compiles a <c>.recomp</c> archive out-of-process into <c>&lt;dataDir&gt;\cache\</c> and loads the entry module.</summary>
    Task<ICartRecompGameModule> CompileAndLoadAsync(
        string recompPackagePath,
        string romSha256Hex,
        string dataDirectory,
        Action<string>? progressCallback = null,
        CancellationToken ct = default);
}

